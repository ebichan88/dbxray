/*
 * DDL作成（テーブル）
 */
-- 親テーブル（コメントは付与しない）
create table sample.department (
    department_id number(10) generated by default as identity constraint department_pkey primary key,
    department_code varchar2(10) not null
        constraint department_department_code_key unique,
    department_name varchar2(50) not null
);

-- 単独テーブル（他のテーブルと参照関係を持たない）
create table sample.parking_spot (
    parking_spot_id number(10) generated by default as identity constraint parking_spot_pkey primary key,
    spot_code varchar2(10) not null
        constraint parking_spot_spot_code_key unique
);

-- 1対多（必須）：department → employee
-- 0..1対多（任意・自己参照）：employee.manager_id → employee
-- 0..1対1（任意・一意）：parking_spot → employee.parking_spot_id
create table sample.employee (
    employee_id number(10) generated by default as identity constraint employee_pkey primary key,
    employee_code varchar2(10) not null
        constraint employee_employee_code_key unique,
    employee_name varchar2(50) not null,
    department_id number(10) not null
        constraint employee_department_id_fkey references sample.department(department_id),
    manager_id number(10)
        constraint employee_manager_id_fkey references sample.employee(employee_id),
    parking_spot_id number(10)
        constraint employee_parking_spot_id_key unique
        constraint employee_parking_spot_id_fkey references sample.parking_spot(parking_spot_id),
    status varchar2(10) default 'ACTIVE' not null
        constraint employee_status_check check (status in ('ACTIVE', 'ON_LEAVE', 'RETIRED')),
    salary number(10, 2) default 0 not null
        constraint employee_salary_check check (salary >= 0),
    profile clob default '{}' not null
        constraint employee_profile_check check (profile is json),
    hired_date date default trunc(sysdate) not null,
    updated_at timestamp default systimestamp not null
);

-- 1対1（必須）：employee ⇔ employee_profile（PKがそのままFK）
create table sample.employee_profile (
    employee_id number(10) constraint employee_profile_pkey primary key
        constraint employee_profile_employee_id_fkey references sample.employee(employee_id),
    address sample.address_type,
    emergency_contact varchar2(50),
    notes clob
);

create table sample.project (
    project_id number(10) generated by default as identity constraint project_pkey primary key,
    project_code varchar2(10) not null
        constraint project_project_code_key unique,
    project_name varchar2(100) not null,
    budget number(12, 2) constraint project_budget_check check (budget >= 0)
);

-- 多対多：project ⇔ employee（複合主キー＝2本の1対多外部キーの組み合わせ）
create table sample.project_assignment (
    project_id number(10) not null
        constraint project_assignment_project_id_fkey references sample.project(project_id),
    employee_id number(10) not null
        constraint project_assignment_employee_id_fkey references sample.employee(employee_id),
    role varchar2(30) default 'MEMBER' not null,
    assigned_at date default trunc(sysdate) not null,
    constraint project_assignment_pkey primary key (project_id, employee_id)
);

create table sample.warehouse_zone (
    warehouse_code varchar2(5) not null,
    zone_code varchar2(5) not null,
    zone_name varchar2(50) not null,
    constraint warehouse_zone_pkey primary key (warehouse_code, zone_code)
);

-- 1対多（必須・複合外部キー）：warehouse_zone → shipment
create table sample.shipment (
    shipment_id number(10) generated by default as identity constraint shipment_pkey primary key,
    warehouse_code varchar2(5) not null,
    zone_code varchar2(5) not null,
    shipped_at timestamp default systimestamp not null,
    constraint shipment_warehouse_code_zone_code_fkey foreign key (warehouse_code, zone_code)
        references sample.warehouse_zone(warehouse_code, zone_code)
);

-- 単独テーブル（関連なし。トリガーからの書き込み先）
create table sample.audit_log (
    log_id number(19) generated by default as identity constraint audit_log_pkey primary key,
    table_name varchar2(50) not null,
    record_id integer,
    action varchar2(10) not null
        constraint audit_log_action_check check (action in ('INSERT', 'UPDATE', 'DELETE')),
    changed_at timestamp default systimestamp not null,
    changed_by varchar2(50)
);

-- パーティション表（月次のレンジパーティション）。PostgreSQLのDEFAULTパーティションの代わりにMAXVALUEのパーティションを持つ
create table sample.attendance (
    attendance_id number(19) not null,
    work_date date not null,
    employee_id number(10) not null
        constraint attendance_employee_id_fkey references sample.employee(employee_id),
    work_minutes integer,
    constraint attendance_pkey primary key (attendance_id, work_date)
)
partition by range (work_date) (
    partition attendance_2025 values less than (date '2026-01-01'),
    partition attendance_2026_01 values less than (date '2026-02-01'),
    partition attendance_2026_02 values less than (date '2026-03-01'),
    partition attendance_2026_03 values less than (date '2026-04-01'),
    partition attendance_default values less than (maxvalue)
);

-- 別スキーマに同名のテーブル（SAMPLE.DEPARTMENT）があっても、索引・カラム等は取り違えず、スキーマごとに取得する
create table sample_archive.department (
    archive_id number(10) constraint department_pkey primary key,
    note varchar2(50)
);
create index sample_archive.idx_archive_department_note on sample_archive.department (note);
-- ALL_*のディクショナリビューには、接続ユーザーが権限を持つオブジェクトだけが現れる
grant select on sample_archive.department to sample;

-- パーティション表を参照するテーブル
create table sample.attendance_note (
    note_id number(10) generated by default as identity constraint attendance_note_pkey primary key,
    attendance_id number(19) not null,
    work_date date not null,
    note clob,
    constraint attendance_note_attendance_id_work_date_fkey foreign key (attendance_id, work_date)
        references sample.attendance(attendance_id, work_date)
);

/*
 * ビュー
 */
create view sample.employee_directory_view as
    select
        e.employee_id,
        e.employee_code,
        e.employee_name,
        d.department_name,
        e.status
    from sample.employee e
    join sample.department d on e.department_id = d.department_id;

-- ビュー・パーティション表・出力対象外のスキーマのテーブルを参照するビュー
create view sample.attendance_monthly_view as
    select
        dv.department_name,
        trunc(a.work_date, 'MM') as work_month,
        sum(a.work_minutes) as total_minutes,
        max(ad.note) as archive_note
    from sample.attendance a
    join sample.employee_directory_view dv on dv.employee_id = a.employee_id
    left join sample_archive.department ad on ad.note = dv.department_name
    group by dv.department_name, trunc(a.work_date, 'MM');

/*
 * マテリアライズドビュー
 */
create materialized view sample.project_summary_mv as
    select
        p.project_id,
        p.project_name,
        count(pa.employee_id) as member_count
    from sample.project p
    left join sample.project_assignment pa on pa.project_id = p.project_id
    group by p.project_id, p.project_name;

