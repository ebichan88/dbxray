/*
 * トリガー（BEFORE / AFTER / INSTEAD OF、ROW / STATEMENT を一通り網羅）
 */
create or replace trigger sample.trg_employee_set_updated_at
    before update on sample.employee
    for each row
begin
    :new.updated_at := systimestamp;
end;
/

create or replace trigger sample.trg_employee_audit
    after insert or update or delete on sample.employee
    for each row
declare
    v_action varchar2(10);
begin
    v_action := case when inserting then 'INSERT' when updating then 'UPDATE' else 'DELETE' end;
    insert into sample.audit_log(table_name, record_id, action, changed_by)
    values ('employee', coalesce(:new.employee_id, :old.employee_id), v_action, user);
end;
/

-- OracleのTRUNCATEトリガーはスキーマ単位のDDLトリガーになるため、文単位のDELETEトリガーで代える
create or replace trigger sample.trg_project_assignment_delete
    after delete on sample.project_assignment
begin
    dbms_output.put_line('sample.project_assignment was deleted');
end;
/

create or replace trigger sample.trg_employee_directory_insert
    instead of insert on sample.employee_directory_view
    for each row
declare
    v_department_id number(10);
begin
    select department_id into v_department_id
    from sample.department
    where department_name = :new.department_name;

    insert into sample.employee(employee_code, employee_name, department_id)
    values (:new.employee_code, :new.employee_name, v_department_id);
end;
/

create or replace trigger sample.trg_attendance_check_work_minutes
    before insert or update on sample.attendance
    for each row
begin
    if :new.work_minutes < 0 then
        raise_application_error(-20001, 'work_minutes must not be negative');
    end if;
end;
/

/*
 * 関数・プロシージャ（Oracleでオーバーロードできるのはパッケージ内のサブプログラムだけのため、パッケージにまとめる）
 */
create or replace package sample.bonus as
    function calculate_bonus(p_salary number, p_rate number) return number deterministic;
    function calculate_bonus(p_salary number) return number deterministic;
end bonus;
/

create or replace package body sample.bonus as
    function calculate_bonus(p_salary number, p_rate number) return number deterministic is
    begin
        return p_salary * p_rate;
    end;

    function calculate_bonus(p_salary number) return number deterministic is
    begin
        return calculate_bonus(p_salary, 0.1);
    end;
end bonus;
/

create or replace procedure sample.raise_salary(p_employee_id number, p_amount number) as
begin
    update sample.employee set salary = salary + p_amount where employee_id = p_employee_id;
end;
/

/*
 * 関数・プロシージャが利用しているテーブル（--previewの機能）のサンプル。
 * パッケージのサブプログラムは、パッケージ本体から同名の本体を切り出し、オーバーロードは引数名で対応付ける
 * （本体の並びは仕様部と逆にしている）。コメント・q'[...]'の中のDMLは拾わない
 */
create or replace package sample.project_ops as
    procedure close_project(p_project_id number);
    procedure close_project(p_project_code varchar2);
    procedure purge_audit_log(p_table_name varchar2);
end project_ops;
/

create or replace package body sample.project_ops as
    -- コードからIDを引いて、ID版に委ねる
    procedure close_project(p_project_code varchar2) is
        v_project_id sample.project.project_id%type;
    begin
        select project_id into v_project_id from sample.project where project_code = p_project_code;
        close_project(v_project_id);
    end close_project;

    procedure close_project(p_project_id number) is
    begin
        /* アサインを外した記録を監査ログへ残す（同じ従業員の記録があれば日時だけ更新する） */
        merge into sample.audit_log l
        using (
            select pa.employee_id
              from sample.project_assignment pa
             where pa.project_id = p_project_id
        ) s
           on (l.table_name = 'project_assignment' and l.record_id = s.employee_id)
         when matched then
            update set l.changed_at = systimestamp
         when not matched then
            insert (table_name, record_id, action, changed_by)
            values ('project_assignment', s.employee_id, 'DELETE', user);

        -- delete from sample.project where project_id = p_project_id;  -- 旧仕様
        delete sample.project_assignment
         where project_id = p_project_id;
        dbms_output.put_line(q'[DELETE FROM sample.project_assignment: 'done']');
    end close_project;

    -- 修飾の無い名前は、定義者権限のため所有者（SAMPLE）のテーブルとみなす。件数は動的SQLで数える
    procedure purge_audit_log(p_table_name varchar2) is
        v_count number;
    begin
        execute immediate 'select count(*) from sample.audit_log where table_name = :1'
            into v_count using p_table_name;
        delete from audit_log
         where table_name = p_table_name
           and changed_at < add_months(systimestamp, -12);
    end purge_audit_log;
end project_ops;
/

